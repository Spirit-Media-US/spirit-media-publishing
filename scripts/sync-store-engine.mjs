// node scripts/sync-store-engine.mjs [FHB repo dir]   (SMP store engine, plan 3fb Phase 3, 2026-11-13)
//
// ONE MASTER: the store engine (catalogue, prices, discounts, far-band, margin floor, Stripe sale metadata and the
// order -> Stripe Checkout form) lives in the FHB repo, src/lib/storeEngine.ts, where its parity test guards it.
// SMP's checkout runs the SAME code: this copies the engine and everything it imports into src/store-engine/
// (same relative layout, so imports are untouched) and writes src/store-engine/MANIFEST.json with the FHB commit
// and each file's sha256. Never edit src/store-engine/ by hand: scripts/store-engine-sync.test.mjs fails the build
// when a file differs from the manifest, and when the FHB source has moved on (re-run this).
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';

export const FILES = [
	'src/lib/storeEngine.ts',
	'src/lib/farBand.ts',
	'src/lib/firstOrderGuard.ts',
	'src/lib/marginGuard.ts',
	'src/lib/order-pricing.ts',
	'src/lib/shipCountries.ts',
	'src/data/book-skus.json',
	'src/data/books.json',
	'src/data/isbn-list.json',
	'src/data/ship-countries.json',
];
export const DEST = 'src/store-engine';
export const sha = (b) => createHash('sha256').update(b).digest('hex');
export const destOf = (f) => path.join(DEST, f.replace(/^src\//, ''));

if (import.meta.url === `file://${process.argv[1]}`) {
	const src = process.argv[2] || process.env.FHB_REPO || '/srv/sites/FHB';
	const commit = execFileSync('git', ['-C', src, 'rev-parse', 'HEAD'], { encoding: 'utf8' }).trim();
	const branch = execFileSync('git', ['-C', src, 'rev-parse', '--abbrev-ref', 'HEAD'], { encoding: 'utf8' }).trim();
	const files = {};
	for (const f of FILES) {
		const b = fs.readFileSync(path.join(src, f));
		fs.mkdirSync(path.dirname(destOf(f)), { recursive: true });
		fs.writeFileSync(destOf(f), b);
		files[f] = sha(b);
	}
	fs.writeFileSync(
		path.join(DEST, 'MANIFEST.json'),
		`${JSON.stringify({ _about: 'GENERATED by scripts/sync-store-engine.mjs from the FHB repo. Do not edit.', source: src, branch, commit, files }, null, 1)}\n`,
	);
	console.log(`store-engine: ${FILES.length} files from ${src} ${branch}@${commit.slice(0, 7)}`);
}
